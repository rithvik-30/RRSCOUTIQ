"""
Phase 5.11: Production-Faithful Walk-Forward Evaluation & Match-Clustered Bootstrap
Evaluates the prospective Top 10 cohorts generated by the official production DLI model
(src/m5_5b_4_3_8/) on unseen future test seasons (2025 and 2026).
Computes:
1. Cohort pooled strike rate / economy vs league baseline in pressure deliveries.
2. Cohort vs eligible non-selected baseline.
3. Match-clustered bootstrap 95% confidence intervals and p-values (B=2,000).
4. Direct comparison table against Phase 5.10 simplified estimates.
"""

import os
import sys
import json
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.abspath("."))

def load_data():
    raw = pd.read_csv("data/processed/m5_3/match_state_full.csv", low_memory=False)
    clean = raw[(raw["is_dli_valid"] == 1) & (raw["ext_is_legal_delivery"] == 1)].copy()
    matches = pd.read_csv("data/extracted/matches.csv")
    m_date_map = matches.set_index("match_id")["match_date"].to_dict()
    clean["match_date"] = clean["match_id"].map(m_date_map)
    clean["year"] = pd.to_datetime(clean["match_date"]).dt.year
    return clean

def run_evaluation():
    rankings_path = "research/phase5_11/prospective_rankings.json"
    if not os.path.exists(rankings_path):
        print(f"Error: {rankings_path} does not exist yet. Ensure model fitting is complete.")
        return

    with open(rankings_path, "r") as f:
        prospective = json.load(f)

    clean = load_data()
    cw = pd.read_csv("data/enriched/player_crosswalk_m5_5.csv")
    p_map = cw.set_index("player_id")["canonical_name"].to_dict()

    results = {}

    for window_key, test_year in [("window_a", 2025), ("window_b", 2026)]:
        print("\n" + "=" * 80)
        print(f"EVALUATING {window_key.upper()}: UNSEEN TEST YEAR {test_year}")
        print("=" * 80)

        win_data = prospective[window_key]
        top10_bat = pd.DataFrame(win_data["top10_batters"])
        top10_bowl = pd.DataFrame(win_data["top10_bowlers"])
        eligible_bat_ids = set(win_data["all_eligible_batters"])
        eligible_bowl_ids = set(win_data["all_eligible_bowlers"])

        top10_bat_ids = set(top10_bat["player_id"])
        top10_bowl_ids = set(top10_bowl["player_id"])

        non_sel_bat_ids = eligible_bat_ids - top10_bat_ids
        non_sel_bowl_ids = eligible_bowl_ids - top10_bowl_ids

        # Test set deliveries
        test_df = clean[clean["year"] == test_year].copy()
        press_test = test_df[test_df["pre_pressure_tier"].isin(["Tier 2: Medium", "Tier 3: High", "Tier 4: Extreme"])].copy()

        unique_matches = press_test["match_id"].unique()
        n_matches = len(unique_matches)
        print(f"Test year {test_year}: {len(test_df)} legal balls, {len(press_test)} pressure balls across {n_matches} matches.")

        # --- Batters Evaluation ---
        top10_bat_press = press_test[press_test["striker_id"].isin(top10_bat_ids)]
        nonsel_bat_press = press_test[press_test["striker_id"].isin(non_sel_bat_ids)]

        bat_top10_balls = len(top10_bat_press)
        bat_top10_runs = top10_bat_press["ext_batter_runs"].sum()
        bat_top10_sr = (bat_top10_runs / bat_top10_balls * 100) if bat_top10_balls > 0 else 0.0

        bat_league_balls = len(press_test)
        bat_league_runs = press_test["ext_batter_runs"].sum()
        bat_league_sr = (bat_league_runs / bat_league_balls * 100) if bat_league_balls > 0 else 0.0

        bat_nonsel_balls = len(nonsel_bat_press)
        bat_nonsel_runs = nonsel_bat_press["ext_batter_runs"].sum()
        bat_nonsel_sr = (bat_nonsel_runs / bat_nonsel_balls * 100) if bat_nonsel_balls > 0 else 0.0

        bat_edge_league = bat_top10_sr - bat_league_sr
        bat_edge_nonsel = bat_top10_sr - bat_nonsel_sr

        print(f"\n--- BATTERS ({test_year}) ---")
        print(f"Prospective Top 10 Batters: {bat_top10_balls} balls, {bat_top10_runs} runs | SR = {bat_top10_sr:.2f}")
        print(f"League Pressure Baseline:   {bat_league_balls} balls, {bat_league_runs} runs | SR = {bat_league_sr:.2f}")
        print(f"Eligible Non-Selected:      {bat_nonsel_balls} balls, {bat_nonsel_runs} runs | SR = {bat_nonsel_sr:.2f}")
        print(f"Edge vs League Baseline:    {bat_edge_league:+.2f} runs/100 balls")
        print(f"Edge vs Eligible Non-Sel:   {bat_edge_nonsel:+.2f} runs/100 balls")

        # Per-player breakdown
        print("\nIndividual Top 10 Batter Exposure in Unseen Test Year:")
        for idx, r in top10_bat.iterrows():
            pid = r["player_id"]
            p_press = press_test[press_test["striker_id"] == pid]
            b_cnt = len(p_press)
            r_cnt = p_press["ext_batter_runs"].sum() if b_cnt > 0 else 0
            sr_val = (r_cnt / b_cnt * 100) if b_cnt > 0 else 0.0
            print(f"  #{idx+1}: {r['name']} | Balls: {b_cnt:3d} | Runs: {r_cnt:3d} | SR: {sr_val:6.2f} (Model Rank LB={r['lb_90']*100:+.2f}%)")

        # --- Bowlers Evaluation ---
        top10_bowl_press = press_test[press_test["bowler_id"].isin(top10_bowl_ids)]
        nonsel_bowl_press = press_test[press_test["bowler_id"].isin(non_sel_bowl_ids)]

        bowl_top10_balls = len(top10_bowl_press)
        bowl_top10_debits = top10_bowl_press["ext_bowler_debit_runs"].sum()
        bowl_top10_econ = (bowl_top10_debits / bowl_top10_balls * 6) if bowl_top10_balls > 0 else 0.0

        bowl_league_balls = len(press_test)
        bowl_league_debits = press_test["ext_bowler_debit_runs"].sum()
        bowl_league_econ = (bowl_league_debits / bowl_league_balls * 6) if bowl_league_balls > 0 else 0.0

        bowl_nonsel_balls = len(nonsel_bowl_press)
        bowl_nonsel_debits = nonsel_bowl_press["ext_bowler_debit_runs"].sum()
        bowl_nonsel_econ = (bowl_nonsel_debits / bowl_nonsel_balls * 6) if bowl_nonsel_balls > 0 else 0.0

        bowl_edge_league = bowl_top10_econ - bowl_league_econ
        bowl_edge_nonsel = bowl_top10_econ - bowl_nonsel_econ

        print(f"\n--- BOWLERS ({test_year}) ---")
        print(f"Prospective Top 10 Bowlers: {bowl_top10_balls} balls, {bowl_top10_debits} debits | Econ = {bowl_top10_econ:.2f} RPO")
        print(f"League Pressure Baseline:   {bowl_league_balls} balls, {bowl_league_debits} debits | Econ = {bowl_league_econ:.2f} RPO")
        print(f"Eligible Non-Selected:      {bowl_nonsel_balls} balls, {bowl_nonsel_debits} debits | Econ = {bowl_nonsel_econ:.2f} RPO")
        print(f"Edge vs League Baseline:    {bowl_edge_league:+.2f} RPO (Negative is better)")
        print(f"Edge vs Eligible Non-Sel:   {bowl_edge_nonsel:+.2f} RPO (Negative is better)")

        print("\nIndividual Top 10 Bowler Exposure in Unseen Test Year:")
        for idx, r in top10_bowl.iterrows():
            pid = r["player_id"]
            p_press = press_test[press_test["bowler_id"] == pid]
            b_cnt = len(p_press)
            d_cnt = p_press["ext_bowler_debit_runs"].sum() if b_cnt > 0 else 0
            econ_val = (d_cnt / b_cnt * 6) if b_cnt > 0 else 0.0
            print(f"  #{idx+1}: {r['name']} | Balls: {b_cnt:3d} | Debits: {d_cnt:3d} | Econ: {econ_val:5.2f} (Model Rank UB={r['ub_90']:+.3f})")

        # --- Match-Clustered Bootstrap (Vectorized Pre-Aggregated) ---
        print("\nComputing Match-Clustered Bootstrap (B=2,000 iterations)...")
        np.random.seed(42)
        B = 2000

        # Pre-aggregate match-level sums for ultra-fast, exact match-clustered bootstrap
        match_stats = []
        for m in unique_matches:
            m_df = press_test[press_test["match_id"] == m]
            
            # League
            lg_b = len(m_df)
            lg_r = m_df["ext_batter_runs"].sum()
            lg_d = m_df["ext_bowler_debit_runs"].sum()
            
            # Top 10 Batters
            m_top_b = m_df[m_df["striker_id"].isin(top10_bat_ids)]
            top_b_balls = len(m_top_b)
            top_b_runs = m_top_b["ext_batter_runs"].sum()
            
            # Non-selected Batters
            m_ns_b = m_df[m_df["striker_id"].isin(non_sel_bat_ids)]
            ns_b_balls = len(m_ns_b)
            ns_b_runs = m_ns_b["ext_batter_runs"].sum()
            
            # Top 10 Bowlers
            m_top_bw = m_df[m_df["bowler_id"].isin(top10_bowl_ids)]
            top_bw_balls = len(m_top_bw)
            top_bw_debits = m_top_bw["ext_bowler_debit_runs"].sum()
            
            # Non-selected Bowlers
            m_ns_bw = m_df[m_df["bowler_id"].isin(non_sel_bowl_ids)]
            ns_bw_balls = len(m_ns_bw)
            ns_bw_debits = m_ns_bw["ext_bowler_debit_runs"].sum()
            
            match_stats.append([
                lg_b, lg_r, lg_d,
                top_b_balls, top_b_runs,
                ns_b_balls, ns_b_runs,
                top_bw_balls, top_bw_debits,
                ns_bw_balls, ns_bw_debits
            ])

        M = np.array(match_stats, dtype=np.float64) # shape: (n_matches, 11)

        boot_bat_edge_league = np.zeros(B)
        boot_bat_edge_nonsel = np.zeros(B)
        boot_bowl_edge_league = np.zeros(B)
        boot_bowl_edge_nonsel = np.zeros(B)

        for b in range(B):
            resample_idx = np.random.choice(n_matches, size=n_matches, replace=True)
            sums = M[resample_idx].sum(axis=0)
            
            # Indices:
            # 0: lg_b, 1: lg_r, 2: lg_d
            # 3: top_b_balls, 4: top_b_runs
            # 5: ns_b_balls, 6: ns_b_runs
            # 7: top_bw_balls, 8: top_bw_debits
            # 9: ns_bw_balls, 10: ns_bw_debits
            
            lg_sr = (sums[1] / sums[0] * 100) if sums[0] > 0 else 0.0
            top_b_sr = (sums[4] / sums[3] * 100) if sums[3] > 0 else lg_sr
            ns_b_sr = (sums[6] / sums[5] * 100) if sums[5] > 0 else lg_sr
            
            boot_bat_edge_league[b] = top_b_sr - lg_sr
            boot_bat_edge_nonsel[b] = top_b_sr - ns_b_sr
            
            lg_econ = (sums[2] / sums[0] * 6.0) if sums[0] > 0 else 0.0
            top_bw_econ = (sums[8] / sums[7] * 6.0) if sums[7] > 0 else lg_econ
            ns_bw_econ = (sums[10] / sums[9] * 6.0) if sums[9] > 0 else lg_econ
            
            boot_bowl_edge_league[b] = top_bw_econ - lg_econ
            boot_bowl_edge_nonsel[b] = top_bw_econ - ns_bw_econ

        def get_ci_and_p(boot_arr, obs_stat, alternative="two-sided"):
            ci_low = np.percentile(boot_arr, 2.5)
            ci_high = np.percentile(boot_arr, 97.5)
            # Two-sided empirical bootstrap p-value relative to 0
            # Fraction of bootstrap replications on opposite side of 0
            if obs_stat >= 0:
                p_val = 2.0 * np.mean(boot_arr <= 0)
            else:
                p_val = 2.0 * np.mean(boot_arr >= 0)
            p_val = min(1.0, max(1.0 / len(boot_arr), p_val))
            return ci_low, ci_high, p_val

        bat_ci_low_lg, bat_ci_high_lg, bat_p_lg = get_ci_and_p(boot_bat_edge_league, bat_edge_league)
        bat_ci_low_ns, bat_ci_high_ns, bat_p_ns = get_ci_and_p(boot_bat_edge_nonsel, bat_edge_nonsel)

        bowl_ci_low_lg, bowl_ci_high_lg, bowl_p_lg = get_ci_and_p(boot_bowl_edge_league, bowl_edge_league)
        bowl_ci_low_ns, bowl_ci_high_ns, bowl_p_ns = get_ci_and_p(boot_bowl_edge_nonsel, bowl_edge_nonsel)

        print("\nMatch-Clustered Bootstrap Inference:")
        print(f"  Batter Edge vs League:  {bat_edge_league:+.2f} [95% CI: {bat_ci_low_lg:+.2f}, {bat_ci_high_lg:+.2f}] | p = {bat_p_lg:.4f}")
        print(f"  Batter Edge vs Non-Sel: {bat_edge_nonsel:+.2f} [95% CI: {bat_ci_low_ns:+.2f}, {bat_ci_high_ns:+.2f}] | p = {bat_p_ns:.4f}")
        print(f"  Bowler Edge vs League:  {bowl_edge_league:+.2f} [95% CI: {bowl_ci_low_lg:+.2f}, {bowl_ci_high_lg:+.2f}] | p = {bowl_p_lg:.4f}")
        print(f"  Bowler Edge vs Non-Sel: {bowl_edge_nonsel:+.2f} [95% CI: {bowl_ci_low_ns:+.2f}, {bowl_ci_high_ns:+.2f}] | p = {bowl_p_ns:.4f}")

        results[window_key] = {
            "test_year": test_year,
            "batters": {
                "top10_balls": bat_top10_balls,
                "top10_runs": int(bat_top10_runs),
                "top10_sr": float(bat_top10_sr),
                "league_sr": float(bat_league_sr),
                "nonsel_sr": float(bat_nonsel_sr),
                "edge_league": float(bat_edge_league),
                "ci_league": [float(bat_ci_low_lg), float(bat_ci_high_lg)],
                "p_league": float(bat_p_lg),
                "edge_nonsel": float(bat_edge_nonsel),
                "ci_nonsel": [float(bat_ci_low_ns), float(bat_ci_high_ns)],
                "p_nonsel": float(bat_p_ns)
            },
            "bowlers": {
                "top10_balls": bowl_top10_balls,
                "top10_debits": int(bowl_top10_debits),
                "top10_econ": float(bowl_top10_econ),
                "league_econ": float(bowl_league_econ),
                "nonsel_econ": float(bowl_nonsel_econ),
                "edge_league": float(bowl_edge_league),
                "ci_league": [float(bowl_ci_low_lg), float(bowl_ci_high_lg)],
                "p_league": float(bowl_p_lg),
                "edge_nonsel": float(bowl_edge_nonsel),
                "ci_nonsel": [float(bowl_ci_low_ns), float(bowl_ci_high_ns)],
                "p_nonsel": float(bowl_p_ns)
            }
        }

    out_path = "research/phase5_11/walk_forward_evaluation_results.json"
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nSaved walk-forward evaluation results to {out_path}")

if __name__ == "__main__":
    run_evaluation()
